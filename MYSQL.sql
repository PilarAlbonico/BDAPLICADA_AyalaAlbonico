

CREATE DATABASE IF NOT EXISTS cipria;
USE cipria;


--  Usuarios del tablero (contraseña guardada solo como hash bcrypt)-
CREATE TABLE IF NOT EXISTS usuarios (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  usuario    VARCHAR(50)  NOT NULL UNIQUE,
  clave_hash VARCHAR(100) NOT NULL
);
-- 
--  Tablas

CREATE TABLE cliente (
  id_cliente       INT AUTO_INCREMENT PRIMARY KEY,
  nombre_cliente   VARCHAR(60) NOT NULL,
  apellido_cliente VARCHAR(60) NOT NULL,
  telefono         VARCHAR(30),
  user_ig          VARCHAR(60)
);

CREATE TABLE categoria (
  id_categoria INT AUTO_INCREMENT PRIMARY KEY,
  nombre       VARCHAR(60) NOT NULL,
  descripcion  VARCHAR(200)
);

CREATE TABLE producto (
  id_producto     INT AUTO_INCREMENT PRIMARY KEY,
  id_categoria    INT NOT NULL,
  nombre_producto VARCHAR(80) NOT NULL,
  precio_costo    DECIMAL(12,2) NOT NULL,
  precio_venta    DECIMAL(12,2) NOT NULL,
  talle           VARCHAR(20),
  stock_actual    INT NOT NULL DEFAULT 0,
  stock_minimo    INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

CREATE TABLE venta (
  id_venta    INT AUTO_INCREMENT PRIMARY KEY,
  id_cliente  INT NOT NULL,
  fecha_venta DATETIME NOT NULL,
  CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

CREATE TABLE detalle_venta (
  id_detalle  INT AUTO_INCREMENT PRIMARY KEY,
  id_producto INT NOT NULL,
  id_venta    INT NOT NULL,
  cantidad    INT NOT NULL,
  subtotal    DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto),
  CONSTRAINT fk_detalle_venta_venta    FOREIGN KEY (id_venta)    REFERENCES venta (id_venta)
);

CREATE TABLE medio_de_pago (
  id_medio_pago INT AUTO_INCREMENT PRIMARY KEY,
  tipo          VARCHAR(40) NOT NULL
);

CREATE TABLE detalle_pago (
  id_detalle_pago INT AUTO_INCREMENT PRIMARY KEY,
  id_medio_pago   INT NOT NULL,
  id_venta        INT NOT NULL,
  monto           DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_detalle_pago_medio FOREIGN KEY (id_medio_pago) REFERENCES medio_de_pago (id_medio_pago),
  CONSTRAINT fk_detalle_pago_venta FOREIGN KEY (id_venta)      REFERENCES venta (id_venta)
);

CREATE TABLE proveedor (
  id_proveedor    INT AUTO_INCREMENT PRIMARY KEY,
  nombre          VARCHAR(80) NOT NULL,
  numero_telefono VARCHAR(30),
  direccion       VARCHAR(120)
);

CREATE TABLE estado (
  id_estado_orden INT AUTO_INCREMENT PRIMARY KEY,
  nombre_estado   VARCHAR(40) NOT NULL
);

CREATE TABLE orden_compra (
  id_orden_compra INT AUTO_INCREMENT PRIMARY KEY,
  id_proveedor    INT NOT NULL,
  id_estado_orden INT NOT NULL,
  fecha_orden     DATETIME NOT NULL,
  CONSTRAINT fk_orden_proveedor FOREIGN KEY (id_proveedor)    REFERENCES proveedor (id_proveedor),
  CONSTRAINT fk_orden_estado    FOREIGN KEY (id_estado_orden) REFERENCES estado (id_estado_orden)
);

CREATE TABLE detalle_orden (
  id_detalle_orden  INT AUTO_INCREMENT PRIMARY KEY,
  id_orden_compra   INT NOT NULL,
  id_producto       INT NOT NULL,
  cantidad_ordenada INT NOT NULL,
  cantidad_recibida INT NOT NULL DEFAULT 0,
  subtotal          DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_detalle_orden_orden    FOREIGN KEY (id_orden_compra) REFERENCES orden_compra (id_orden_compra),
  CONSTRAINT fk_detalle_orden_producto FOREIGN KEY (id_producto)     REFERENCES producto (id_producto)
);

-- Índices para las consultas del tablero (filtros por fecha)
CREATE INDEX ix_venta_fecha ON venta (fecha_venta);
CREATE INDEX ix_orden_fecha ON orden_compra (fecha_orden);


